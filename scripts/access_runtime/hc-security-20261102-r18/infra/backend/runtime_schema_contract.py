def check_runtime_schema(execute, domain):
    # Names are code-owned constants. SELECT validates both shape and access
    # without granting runtime ownership or making requests perform migrations.
    try:
        for table, columns in REQUIRED[domain].items():
            execute('select ' + ','.join('"'+c+'"' for c in columns) + ' from hc.' + table + ' limit 0')
    except Exception as exc:
        raise RuntimeError('Missing/inaccessible HC schema for ' + domain + '; run migrate_hc39.py --plan / --apply explicitly.') from exc
